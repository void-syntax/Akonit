def flag_emoji(code: str) -> str:
    """ISO code -> regional indicator flag emoji."""
    return "".join(chr(0x1F1E6 + ord(c) - ord("A")) for c in code.upper())


def slugify_country(name: str) -> str:
    return name.lower().replace(" ", "-")